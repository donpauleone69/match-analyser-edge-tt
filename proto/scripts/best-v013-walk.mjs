const results = []
let cur = null
let fitBad = []
const begin = (id) => {
  cur = { id, fails: [] }
  fitBad = []
}
const expect = (name, got, want) => {
  const ok = typeof want === 'function' ? want(got) : JSON.stringify(got) === JSON.stringify(want)
  if (!ok) cur.fails.push(`${name}: got ${JSON.stringify(got)} want ${typeof want === 'function' ? 'check' : JSON.stringify(want)}`)
}
const fitHere = async (where) => {
  const bad = await fit(page)
  if (bad) fitBad.push(`${where}: ${bad}`)
}
const done = () => {
  if (fitBad.length) cur.fails.push(...fitBad)
  results.push(cur)
  console.log(`${cur.fails.length ? 'FAIL' : 'pass'} ${cur.id}${cur.fails.length ? '\n   ' + cur.fails.join('\n   ') : ''}`)
}
const S = () => state(page)
const step = async (where) => {
  const s = await S()
  await fitHere(where)
  return s
}
const listLines = () =>
  page.evaluate(() => {
    const rows = [...document.querySelectorAll('[aria-label^="Rally "][aria-pressed]')]
    const byNo = []
    for (const b of rows) byNo[Number(b.getAttribute('aria-label').slice(6)) - 1] = b.textContent.replace(/\s+/g, ' ').trim()
    return byNo
  })
const firstServer = (name) => async () => {
  await tapRally(page, 1)
  await end(page, 'Winner')
  await point(page, name)
  await page.waitForTimeout(300)
}
/** Rally one is an ace. Then rally 2 is served by the ace's server. */
const setup = async (server = 'You') => {
  await fresh(page)
  await firstServer(server)()
}
const run = async (id, fn) => {
  if (only && !only.includes(id)) return
  begin(id)
  try {
    await fn()
  } catch (e) {
    cur.fails.push('threw ' + String(e).slice(0, 300))
  }
  done()
}
const seq = []
const track = async () => {
  const s = await S()
  seq.push(s.step === 'shots' ? `shot ${s.page}` : s.step ?? (s.saved ? 'saved' : s.mode))
  await fitHere(seq[seq.length - 1])
  return s
}

