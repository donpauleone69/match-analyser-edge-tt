const tapAddAt = async (pick) => {
  // pick(contacts, t) says when to tap, in rally time
  for (let i = 0; i < 400; i++) {
    const { t, cs } = await page.evaluate(() => {
      const el = document.querySelector('.tag-set')
      return { t: Number(el.dataset.time), cs: el.dataset.contacts.split(',').map(Number) }
    })
    if (pick(cs, t)) {
      await page.click('[data-tap-add]')
      await page.waitForTimeout(250)
      return true
    }
    await page.waitForTimeout(15)
  }
  return false
}

